// Generates articles.js from the Bondsreglement. Run with: node tools/extract-articles.mjs
// The article texts are copied verbatim, only page footers and form feeds are removed.
// test/articles.test.js guards that this stays the case.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

export const PDF = "bronnen/bondsreglement-2026.pdf";

export const WANTED = [
  "3.1.1",
  "3.1.3",
  "5.1.1",
  "5.2.4",
  "5.2.5",
  "5.3.1",
  "5.3.2",
  "5.3.3",
  "5.3.4",
  "5.3.5",
  "5.3.5.1",
  "5.3.5.2",
  "5.3.5.3",
  "5.3.5.4",
  "5.3.6",
  "5.3.6.1",
];

// Titles that span multiple lines in the PDF and therefore do not come out of the heading
// line in full.
const TITLE_CORRECTION = {
  "5.3.3": "Niveaubepaling niet clubgebonden speler en clubgebonden speler zonder teamlijst",
};

export function readLines(pdf = PDF) {
  const raw = execFileSync("pdftotext", ["-layout", pdf, "-"], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  return raw
    .replace(/\f/g, "")
    .split("\n")
    .filter((line) => !/KNHB Bondsreglement \d+\s*$/.test(line))
    .map((line) => line.replace(/\s+$/, ""));
}

// Strips redundant spaces so an indented continuation line can be compared with the rest of
// the title.
function normalize(text) {
  return text.replace(/\s+/g, " ").trim();
}

export function extract(lines) {
  const HEADING = /^(\d+(?:\.\d+)+)\s+(\S.*)$/;
  const headings = [];
  lines.forEach((line, index) => {
    const match = line.match(HEADING);
    if (match && !match[2].includes("....")) {
      headings.push({ index, number: match[1], title: match[2] });
    }
  });

  const articles = {};
  for (const number of WANTED) {
    const found = headings.filter((heading) => heading.number === number);
    if (found.length !== 1) {
      throw new Error(`article ${number}: found ${found.length} headings, expected exactly 1`);
    }
    const heading = found[0];
    const next = headings.find((other) => other.index > heading.index);
    const end = next ? next.index : lines.length;
    let textLines = lines.slice(heading.index + 1, end);

    // When the title spans multiple lines, the continuation lines of the heading end up at
    // the start of textLines. Build the title up step by step and skip exactly as many lines
    // as are needed to arrive at the corrected title.
    const title = TITLE_CORRECTION[number] || heading.title;
    if (TITLE_CORRECTION[number]) {
      const target = normalize(title);
      let built = normalize(heading.title);
      while (built !== target && textLines.length > 0 && target.startsWith(`${built} `)) {
        built = normalize(`${built} ${textLines[0]}`);
        textLines = textLines.slice(1);
      }
      if (built !== target) {
        throw new Error(`title correction for article ${number} does not match the lines after the heading`);
      }
    }

    const text = textLines
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim();
    if (text.length === 0) throw new Error(`article ${number} has no text`);
    articles[number] = { title, text };
  }
  return articles;
}

function write(articles) {
  const header = [
    "// Generated by tools/extract-articles.mjs. Do not edit by hand.",
    "// Source: bronnen/bondsreglement-2026.pdf, KNHB Bondsreglement 2026.",
    "",
    "export const ARTICLES = ",
  ].join("\n");
  writeFileSync("articles.js", `${header}${JSON.stringify(articles, null, 2)};\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const articles = extract(readLines());
  write(articles);
  console.log(`${Object.keys(articles).length} articles written to articles.js`);
}
